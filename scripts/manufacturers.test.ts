import assert from 'node:assert/strict';
import {manufacturerLinks} from '../lib/manufacturers';
import {batchInput} from '../lib/batch-input';
import {newItem,cloneItem,repeatFields,emptyProduct,type Batch} from '../lib/batch';
import {serializeProduct} from '../lib/catalog';

const template={...emptyProduct,manufacturer:{code:'OPE_123',country:'CN'}};
const item=newItem(template,'12345678','95069100');
const batch:Batch={id:crypto.randomUUID(),company:'12345678',ncm:'95069100',template,items:[item]};
assert.deepEqual(item.manufacturer,template.manufacturer);
assert.throws(()=>manufacturerLinks(batch),/código do produto no Portal/);
item.portalProductCode='0089';
assert.deepEqual(manufacturerLinks(batch),[{seq:1,cpfCnpjRaiz:'12345678',codigoProduto:89,codigoPais:'CN',codigoOperadorEstrangeiro:'OPE_123',conhecido:true,vincular:true}]);
const old={...batch,template:{...emptyProduct},items:[{...newItem(emptyProduct,'12345678','95069100')}]};
assert.equal(batchInput.safeParse(old).success,true);
assert.throws(()=>manufacturerLinks(old),/pelo menos um item/);
const parsed=batchInput.parse(batch);
assert.equal(parsed.items[0].portalProductCode,'0089');
assert.equal(parsed.items[0].manufacturer?.code,'OPE_123');
assert.equal(cloneItem(item).portalProductCode,undefined);
assert.equal(newItem(item,batch.company,batch.ncm).portalProductCode,undefined);
const blank=newItem(emptyProduct,batch.company,batch.ncm);
const assigned=repeatFields([blank],template,new Set([blank.id!]),['manufacturer'],false)[0];
assert.deepEqual(assigned.manufacturer,template.manufacturer);
assigned.manufacturer={code:'OPE_999',country:'DE'};
assert.equal(repeatFields([assigned],template,new Set([assigned.id!]),['manufacturer'],false)[0].manufacturer?.code,'OPE_999');
assert.equal(repeatFields([assigned],template,new Set([assigned.id!]),['manufacturer'],true)[0].manufacturer?.code,'OPE_123');
assert.equal(repeatFields([assigned],template,new Set(),['manufacturer'],true)[0].manufacturer?.code,'OPE_999');
const wire=serializeProduct(item,{ncm:batch.ncm,attributes:[],date:'2026-11-23',version:'1',live:true},1);
assert.equal('manufacturer' in wire,false);
assert.equal('portalProductCode' in wire,false);
assert.equal('codigo' in wire,false);
const hundred={...batch,items:Array.from({length:100},(_,i)=>({...newItem(template,batch.company,batch.ncm),portalProductCode:String(500+i)}))};
assert.equal(manufacturerLinks(hundred).length,100);
assert.equal(manufacturerLinks(hundred)[99].seq,100);
assert.throws(()=>manufacturerLinks({...hundred,items:[...hundred.items,item]}),/100 itens/);
assert.throws(()=>manufacturerLinks({...batch,items:[item,{...item}]}),/repetido/);
assert.throws(()=>manufacturerLinks({...batch,items:[{...item,manufacturer:{code:'OPE_123',country:''}}]}),/país/);
assert.throws(()=>manufacturerLinks({...batch,items:[{...item,manufacturer:{code:'',country:'CN'}}]}),/código do fabricante/);
assert.throws(()=>manufacturerLinks({...batch,items:[{...item,portalProductCode:'0'}]}),/código do produto/);
assert.throws(()=>manufacturerLinks({...batch,items:[{...item,manufacturer:{code:'OPE_123',country:'BR'}}]}),/país/);
assert.equal(manufacturerLinks({...batch,items:[blank,item]})[0].seq,1);
console.log('Manufacturer tests passed: draft compatibility, persistence, inheritance, repetition, cloning, payload separation, validation and 100-item limit.');
